ROOT = Path(__file__).resolve().parents[1]


def load_module(name: str, relative: str):
    spec = importlib.util.spec_from_file_location(name, ROOT / relative)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


VALIDATOR = load_module(
    "validate_qwen3vl_gt_direct_teacher_test",
    "tools/validate_qwen3vl_gt_direct_teacher.py",
)
RUNNER_FIXTURE = load_module(
    "qwen3vl_gt_direct_teacher_runner_fixture_for_validator",
    "tests/test_qwen3vl_gt_direct_teacher.py",
)
TEACHER = RUNNER_FIXTURE.TEACHER
BASE = RUNNER_FIXTURE.BASE
CONFIG_PATH = ROOT / "configs" / "qwen3vl_gt_direct_teacher_0804.json"


