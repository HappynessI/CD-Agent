    def test_append_only_output_writes_report_manifest_then_refuses_overwrite(self):
        with tempfile.TemporaryDirectory() as directory:
            target = Path(directory) / "validation"
            report = {"schema_id": "report", "scientific_conclusion": "inconclusive"}
            manifest = {"schema_id": "manifest"}
            VALIDATOR.write_outputs(target, report, manifest)
            written_manifest = json.loads((target / "artifact_manifest.json").read_text())
            self.assertEqual(
                written_manifest["validation_report"]["sha256"],
                VALIDATOR.sha256_file(target / "validation_report.json"),
            )
            with self.assertRaisesRegex(VALIDATOR.ValidationError, "overwrite"):
                VALIDATOR.write_outputs(target, report, manifest)


