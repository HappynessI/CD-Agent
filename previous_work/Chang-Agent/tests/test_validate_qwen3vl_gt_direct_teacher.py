    def validate_record(self, record=None):
        return VALIDATOR.validate_episode(
            self.record if record is None else record,
            root=self.artifact_root,
            expected_sample_id="train_407_r3c2",
            source_episode_sha256="5" * 64,
            config=self.config,
            context=self.context,
        )

    def exact_96_catalog(self):
        t1 = np.zeros((256, 256), dtype=bool)
        t2 = np.zeros_like(t1)
        ground_truth = np.zeros_like(t1)
        for y, x in ((20, 20), (20, 80), (80, 20), (80, 80)):
            t1[y : y + 5, x : x + 5] = True
            t2[y : y + 5, x : x + 5] = True
            ground_truth[y : y + 5, x : x + 5] = True
        change = np.zeros_like(t1)
        hashes = {
            "t1": BASE.mask_sha256(t1),
            "t2": BASE.mask_sha256(t2),
            "change": BASE.mask_sha256(change),
        }
        source = VALIDATOR.StateArtifact(
            {"t1": t1, "t2": t2, "change": change},
            hashes,
            VALIDATOR.state_sha256(hashes),
            {},
        )
        state = BASE.ChangeState(
            np.zeros((256, 256, 3), dtype=np.uint8),
            np.zeros((256, 256, 3), dtype=np.uint8),
            "building",
            t1,
            t2,
            change,
        )
        actions, catalog = TEACHER.build_teacher_candidates(
            RUNNER_FIXTURE.runtime_episode(),
            state,
            ground_truth,
            1,
            geometry_mode="wide",
            candidate_limit=96,
        )
        candidates = [{"candidate_id": item.candidate_id} for item in actions]
        sample = {"semantic": {"t1_state": "background", "t2_state": "building"}}
        return source, ground_truth, catalog, candidates, sample

    def test_real_environment_fixture_passes_full_independent_episode_validation(self):
        episode = self.validate_record()
        self.assertEqual(episode.winning_track, "matched_safe")
        self.assertEqual(episode.tracks["matched_safe"].selected_steps, 1)
        self.assertFalse(self.record["training_authorized"])

    def test_teacher_seed_tamper_fails_closed(self):
        record = copy.deepcopy(self.record)
        candidate = record["tracks"]["matched_safe"]["selection_rounds"][0]["candidates"][0]
        candidate["teacher_geometry"]["component_seed_pixels"] = [0, 0]
        candidate["proposal"] = copy.deepcopy(candidate["teacher_geometry"])
        with self.assertRaisesRegex(VALIDATOR.ValidationError, "seed"):
            self.validate_record(record)

