    def test_global_coarse_conclusions_use_only_slurm_allowed_enum(self):
        def tracks(winner):
            result = {}
            for name in VALIDATOR.TRACK_NAMES:
                executed = winner is None or VALIDATOR.TRACK_NAMES.index(name) <= VALIDATOR.TRACK_NAMES.index(winner)
                result[name] = VALIDATOR.ValidatedTrack(
                    name, executed, name == winner, 0, 0, 0, 0, 0, 0, 0,
                    {}, {}, "endpoint_reached" if name == winner else "no_eligible_beneficial",
                )
            return result

        def episode(index, winner):
            return VALIDATOR.ValidatedEpisode(
                f"sample-{index}", f"parent-{index}", "train", "a" * 64,
                winner,
                "teacher_endpoint_success" if winner else "teacher_endpoint_not_reached",
                "detail", tracks(winner), {},
            )

        cases = {
            "proposal_bottleneck_supported": ["matched_safe"] * 4,
            "tool_upper_bound_supported": ["wide_raw"] * 4,
            "greedy_protocol_inconclusive": [None] * 4,
            "inconclusive": ["matched_safe", None, "wide_raw", None],
        }
        for expected, winners in cases.items():
            with self.subTest(expected=expected):
                report = VALIDATOR.build_report(
                    [episode(index, winner) for index, winner in enumerate(winners)],
                    self.context,
                    [],
                    "b" * 40,
                    "c" * 64,
                )
                self.assertEqual(report["scientific_conclusion"], expected)
                self.assertTrue(report["teacher_only"])
                self.assertFalse(report["training_authorized"])

