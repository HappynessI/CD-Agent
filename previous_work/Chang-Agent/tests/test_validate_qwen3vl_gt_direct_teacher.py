    def test_same_pixel_count_spatial_gt_tamper_fails_against_frozen_parent(self):
        record = copy.deepcopy(self.record)
        tampered = np.zeros((256, 256), dtype=np.uint8)
        tampered[1, 1] = 1
        path = self.artifact_root / "tampered-spatial-gt.npy"
        with path.open("wb") as stream:
            np.save(stream, tampered)
        record["gt_mask"] = {
            "path": str(path.relative_to(self.artifact_root)),
            "sha256": VALIDATOR.sha256_file(path),
            "size_bytes": path.stat().st_size,
            "mask_sha256": VALIDATOR.mask_sha256(tampered != 0),
            "shape": [256, 256],
        }
        with self.assertRaisesRegex(VALIDATOR.ValidationError, "differs spatially"):
            self.validate_record(record)

